"""Pin the raw results tree by content, so a copy can be checked against ours.

`results/` is too large for git, which leaves a gap the rest of this repo is
built to avoid: every derived artifact is committed and reproducible, but the
thing they all derive FROM travels out of band. Someone who fetches the archive
has no way to tell whether they got the tree the paper was built on, a partial
download, or a later re-run -- and this project has already been bitten twice by
files that looked right and were not (truncated cells that a resume mistook for
finished work; 10,000 rows of the wrong instrument under the right filename).

So the manifest is committed and the data is not. It records, per cell, the
SHA-256 of the file, its size, its row count, and whether a `.done` marker sits
beside it. Verifying is then a content check rather than a promise:

    python3 scripts/results_manifest.py            # write data/manifests/results_manifest.json
    python3 scripts/results_manifest.py --verify   # check the tree against it

--verify exits non-zero on any mismatch, and names which kind: changed, missing,
or present-but-unlisted. An unlisted file is reported rather than ignored,
because a stray cell in the tree is exactly how an unblessed re-run gets into an
analysis that folds over `*.jsonl`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

CHUNK = 1 << 20


def digest(path: Path) -> tuple[str, int, int]:
    """-> (sha256, bytes, lines). Streamed, because cells reach ~100MB."""
    h, size, lines = hashlib.sha256(), 0, 0
    with path.open("rb") as fh:
        while chunk := fh.read(CHUNK):
            h.update(chunk)
            size += len(chunk)
            lines += chunk.count(b"\n")
    return h.hexdigest(), size, lines


def build(results: Path) -> dict:
    files = {}
    for p in sorted(results.glob("*.jsonl")):
        sha, size, lines = digest(p)
        files[p.name] = {"sha256": sha, "bytes": size, "rows": lines,
                         "done_marker": p.with_suffix(".jsonl.done").exists()}
    return {
        "_comment": "Generated by scripts/results_manifest.py. The raw results "
                    "tree is too large for git; this pins it by content so a "
                    "fetched copy can be verified as the one the paper used.",
        "n_files": len(files),
        "total_bytes": sum(f["bytes"] for f in files.values()),
        "total_rows": sum(f["rows"] for f in files.values()),
        # One hash over the per-file hashes: a single value to quote in the
        # paper, which changes if any cell does.
        "tree_sha256": hashlib.sha256(
            "".join(f"{n}:{f['sha256']}\n" for n, f in sorted(files.items()))
            .encode()).hexdigest(),
        "files": files,
    }


def verify(results: Path, manifest: dict) -> list[str]:
    listed = manifest["files"]
    problems = []
    for name, want in sorted(listed.items()):
        p = results / name
        if not p.exists():
            problems.append(f"MISSING   {name}")
            continue
        sha, size, lines = digest(p)
        if sha != want["sha256"]:
            problems.append(
                f"CHANGED   {name}  ({want['rows']} rows/{want['bytes']}B "
                f"expected, {lines}/{size} found)")
    for p in sorted(results.glob("*.jsonl")):
        if p.name not in listed:
            problems.append(
                f"UNLISTED  {p.name}  -- not in the manifest; an analysis that "
                f"folds over *.jsonl would silently include it")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="data/manifests/results_manifest.json")
    ap.add_argument("--verify", action="store_true")
    args = ap.parse_args()

    results, out = Path(args.results), Path(args.out)
    if not results.is_dir():
        print(f"no results tree at {results}/ -- fetch it first "
              f"(see README), then re-run.")
        return 1

    if args.verify:
        if not out.exists():
            print(f"no manifest at {out}; nothing to verify against.")
            return 1
        manifest = json.loads(out.read_text())
        problems = verify(results, manifest)
        if problems:
            print(f"=== {len(problems)} problem(s) against {out} ===")
            for p in problems:
                print(f"  {p}")
            print("\nFAIL: this tree is not the one the manifest pins.")
            return 1
        print(f"OK: {manifest['n_files']} files match {out}")
        print(f"    tree_sha256 {manifest['tree_sha256'][:16]}")
        return 0

    manifest = build(results)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {out}  ({manifest['n_files']} files, "
          f"{manifest['total_bytes'] / 1e6:.0f} MB, "
          f"{manifest['total_rows']:,} rows)")
    print(f"  tree_sha256 {manifest['tree_sha256']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
